package io.github.dumahuch.pogodaapp.home

/**
 * Где стоит значок погоды рядом с цифрами температуры (решение Димы 07.11.2026, step-30): значки выровнены по нижнему
 * краю облака, у всех облако на одной высоте; штрихи дождя, молния и снег свисают ниже. Весь значок приподнят. У тумана
 * и ветра облака нет: по этому краю стоит низ рисунка. С step-42 у обоих наборов одна форма, поэтому числа общие.
 * Все числа в единицах значка (квадрат 24 × 24), сверху вниз.
 */
internal fun glyphCloudBottom(icon: HeroIcon): Float = GlyphScenes.of(icon).cloudBottom

/**
 * На сколько единиц значка нижний край облака стоит выше нижнего края цифр. Над значком в той же колонке стоит градус,
 * а у облака с солнцем верх значка выше всего: подъём подобран так, чтобы солнце не доставало до градуса.
 */
internal const val GLYPH_LIFT = 5f
